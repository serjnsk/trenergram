const trMatch = (cond, p) => !cond || Object.entries(cond).every(([k, v]) => [].concat(v).includes(p[k]));
const trAdd = (iso, n) => { const d = new Date(iso + 'T00:00:00'); d.setDate(d.getDate() + n);
  return d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0'); };
const trToday = () => trAdd((d => d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0'))(new Date()), 0);
const trEval = (w, code) => { try { return w.eval(code); } catch (e) { return undefined; } };
const trViews = (id, p) => (TR_SCREENS[id].views || []).filter(v => trMatch(v.if, p));
/* Адрес вида: свой url вида или адрес экрана + параметры сценария */
function trUrl(id, vid, p) {
  const sc = TR_SCREENS[id], t = trToday();
  const v = (sc.views || []).find(x => x.id === vid) || {};
  let u = v.url || sc.page;
  if (typeof u === 'function') u = u(p, t);
  const [path, hash] = u.split('#');
  const q = trQuery(p, path);
  return path + (q ? (path.includes('?') ? '&' : '?') + q : '') + (hash ? '#' + hash : '');
}

/* Шаги вида на открытой странице. Один исполнитель на стенд и на проверку
   скриптом: в стенде win — окно фрейма, в проверке — окно самой страницы. */
async function trRun(win, steps) {
  const d = win.document, sleep = ms => new Promise(r => win.setTimeout(r, ms));
  for (const [k, a, b] of steps || []) {
    if (k === 'wait') { await sleep(a); continue; }
    if (k === 'js') { try { win.eval(a); } catch (e) { console.warn('trRun', a, e); } await sleep(60); continue; }
    const el = d.querySelector(a);
    if (!el) { console.warn('trRun: нет', a); continue; }
    if (k === 'click') { el.scrollIntoView({ block: 'center' }); el.click(); }
    if (k === 'type') {
      el.scrollIntoView({ block: 'center' });
      el.focus();
      if ('value' in el && el.tagName !== 'DIV') el.value = b; else el.textContent = b;
      try { const s = win.getSelection(), r = d.createRange(); r.selectNodeContents(el); r.collapse(false); s.removeAllRanges(); s.addRange(r); } catch (e) {}
      el.dispatchEvent(new win.InputEvent('input', { bubbles: true, data: b, inputType: 'insertText' }));
    }
    await sleep(80);
  }
}
/* Какой вид открыт сейчас — по признакам sel; иначе null */
function trDetect(win, id, p) {
  const d = win.document;
  const has = s => { if (!s) return false; const [css, txt] = [].concat(s);
    return [...d.querySelectorAll(css)].some(e => !txt || e.textContent.toLowerCase().includes(txt.toLowerCase())); };
  const vs = trViews(id, p).filter(v => v.sel);
  for (let i = vs.length - 1; i >= 0; i--) if (has(vs[i].sel)) return vs[i].id;
  return null;
}
