/* Параметры → адрес страницы. Режим тренера кабинет читает из ?new= и
   помнит в localStorage (tg.new); стенд дублирует его туда сам (trMode). */
const trQuery = (p, page) => {
  const q = ['new=' + ({ active: '0', new: '1', done: 'done' })[p.trainer]];
  if (/^profile\.html/.test(page)) q.push('payout=' + (p.payout === 'on' ? 1 : 0));
  if (p.data === 'long') q.push('long=1');
  return q.join('&');
};
/* «Новый» и «Шаги пройдены» живут в одном состоянии кабинета (trenergram.state.new).
   Сменили режим в стенде — начинаем его с чистого листа: иначе «Новый» после
   «Шагов пройдено» открывался бы с отмеченными шагами. Пока режим тот же —
   прогресс чек-листа, пройденного внутри телефона, сохраняется (tr.applied). */
const trMode = (p, store) => { try {
  const was = store.getItem('tr.applied');
  store.setItem('tg.new', p.trainer === 'active' ? '' : '1');
  if (p.trainer !== 'active' && was !== p.trainer) store.removeItem('trenergram.state.new');
  store.setItem('tr.applied', p.trainer);
  store.setItem('tr.long', p.data === 'long' ? '1' : '');
} catch (e) {} };

