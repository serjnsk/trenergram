/* ── сценарий по параметрам — общий для стенда и приложения ── */
const clDefaults = () => Object.fromEntries(CL_PARAMS.map(x => [x.id, x.opts[0][0]]));
const clNorm = p => {
  const q = Object.assign(clDefaults(), p || {});
  CL_PARAMS.forEach(x => { if (!x.opts.some(o => o[0] === q[x.id])) q[x.id] = x.opts[0][0]; });
  return q;
};
/* Условие шага: значение или список допустимых значений */
const clMatch = (cond, p) => !cond || Object.entries(cond).every(([k, v]) => [].concat(v).includes(p[k]));
const clFlow = p => CL_MAP.map(f => ({ flow: f.flow, items: f.items.filter(it => clMatch(it.if, p)) }));
/* Экраны сценария по порядку: { id, v } без повторов */
const clSeq = p => {
  const out = [];
  clFlow(p).forEach(f => f.items.forEach(it => {
    const id = it.s || it.goto;
    if (id && !out.some(o => o.id === id)) out.push({ id, v: it.v || '' });
  }));
  return out;
};
const clInFlow = (id, p) => clSeq(p).find(o => o.id === id);
const clNext = (id, p) => { const s = clSeq(p), i = s.findIndex(o => o.id === id); return i > -1 && s[i + 1] ? s[i + 1].id : ''; };
/* Все сочетания параметров — чтобы найти сценарий, где есть нужный экран */
const clCombos = (() => {
  let all = [{}];
  CL_PARAMS.forEach(x => { all = all.flatMap(c => x.opts.map(o => Object.assign({}, c, { [x.id]: o[0] }))); });
  const seen = new Set();
  return all.map(clNorm).filter(c => { const k = JSON.stringify(c); return !seen.has(k) && seen.add(k); });
})();
/* Ближайшие к текущим параметры, при которых экран есть в сценарии */
const clNearest = (id, p, v) => {
  if (clInFlow(id, p) && (!v || clInFlow(id, p).v === v || !clInFlow(id, p).v)) return p;
  const diff = c => CL_PARAMS.filter(x => c[x.id] !== p[x.id]).length;
  return clCombos.filter(c => { const o = clInFlow(id, c); return o && (!v || !o.v || o.v === v); })
    .sort((a, b) => diff(a) - diff(b))[0] || p;
};

