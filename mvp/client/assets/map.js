/* Первый экран и вид по умолчанию — общие для стенда и приложения */
const CL_START = 'splash';
const clView = (id, v) => {
  const sc = CL_SCREENS[id];
  if (!sc || !sc.views || !sc.views.length) return '';
  return sc.views.some(x => x.id === v) ? v : sc.views[0].id;
};
/* Переходы экрана для вида и параметров; @next — дальше по сценарию */
const clLinks = (id, v, p) => (CL_SCREENS[id].links || [])
  .filter(l => !l.when || l.when === v)
  .map(l => l.to === '@next' ? Object.assign({}, l, { to: clNext(id, p), next: true }) : l)
  .filter(l => l.to);
